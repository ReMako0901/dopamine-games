# 100本のゲーム設計を生成する：20系統 × 5バリエーション
# 出力: prompts100/batch-01.md .. batch-20.md（各5本分）, manifest.tsv
import os

COMMON = """## 共通ルール
- 各ゲームは指定されたファイル名の単一HTMLファイル。外部ライブラリ禁止、Canvas 2D＋素のJS、自前の軽量物理。
- スマホ縦画面（幅393px基準）フルスクリーン、暗い背景。
- 表示は巨大な数字1つだけ：スコアを全桁カンマ区切り（省略表記禁止）、桁が増えたらフォント自動縮小で1行に収める。
- ボタン・パネル・説明文などのUIは置かない。操作はタップのみ。ダブルタップでリセット。
- 描画はベタ塗り中心で軽く。shadowBlur・グラデーション・大量パーティクル禁止。玉同士の衝突計算は原則しない。
- JSエラーなし。余計なファイルは作らない。
"""

# (slug, 名前, 仕様テンプレ)  {twist} が差し替わる
FAMILIES = [
 ("split", "分裂アリーナ", "玉が1個、{stage}の中を跳ね回る。壁や障害物に当たるたびに玉が1個増える（親子0.5秒クールダウン）。数字は玉の総数。タップで玉を放つ（最初だけ）。{twist}"),
 ("peg", "ペグ落下", "上から玉が自動で落ち、{stage}のペグに当たるたび1個増える。下の皿（倍率つき）に入るとスコア加算。数字はスコア。{twist}"),
 ("chain", "連鎖爆発", "玉が{count}個漂う。タップした玉が爆発し、半径内の玉が誘爆して連鎖する。スコアは爆発数×連鎖の深さ。{twist}"),
 ("merge", "合体ドロップ", "タップ位置から数字つき玉（2）を落とす。同じ数字同士が触れると合体して2倍になる。スコアは合体の合計。{twist}"),
 ("gate", "ゲート倍増", "玉が上から流れ落ち、{stage}にある×2ゲートをくぐると2個に増え、×0ゲートで消える。下に届くとスコア+1。{twist}"),
 ("idle", "放置数字", "数字が勝手に増え続ける。増加量自体が複利で増える。タップで増加量×5を即加算。localStorage保存と閉じてる間の加算つき。内部はBigInt。{twist}"),
 ("orbit", "軌道分裂", "中心の重力源の周りを玉が回る。玉が中心核に触れると分裂して2個になる。数字は玉の総数。タップで玉を1個投入。{twist}"),
 ("grow", "巨大化分裂", "玉が跳ねるたび少しずつ大きくなる。一定サイズを超えると2個に分裂して小さく戻る。数字は分裂の累計。{stage}が舞台。{twist}"),
 ("catch", "受け皿爆発", "上から玉が降ってくる。下の受け皿（左右に自動で動く）で受けると玉が2個に増えて跳ね返る。落とすと消える。数字は受けた累計。{twist}"),
 ("spiral", "渦巻き増殖", "玉が渦巻き状の壁に沿って転がり、壁の継ぎ目に当たるたび増える。数字は玉の総数。タップで投入。{twist}"),
 ("rain", "玉の雨", "画面全体に玉が雨のように降る。下のラインに届いた玉の数だけスコアが増え、時々「分裂の雨」で一気に倍になる。{twist}"),
 ("pinball", "自動ピンボール", "玉が{stage}を跳ね回り、光るバンパーに当たると分裂する。フリッパーは自動で動く。数字は玉の総数。{twist}"),
 ("fractal", "タップ開花", "タップした場所から玉が放射状に生まれ、その玉が壁に当たるとさらに小さい玉を生む。数字は生まれた玉の累計。{twist}"),
 ("magnet", "磁石群れ", "玉が磁石ポイントに引き寄せられて群れる。磁石に触れた玉は分裂する。磁石はゆっくり移動する。数字は玉の総数。{twist}"),
 ("laser", "反射レーザー玉", "玉が鏡の壁で反射しながら飛び、鏡に当たるたび分裂する。{stage}に鏡が配置されている。数字は玉の総数。{twist}"),
 ("pendulum", "振り子分裂", "振り子のように揺れる玉が、振り幅の端の壁に触れるたび分裂する。分裂した玉も揺れる。数字は玉の総数。{twist}"),
 ("waterfall", "滝壺倍増", "玉が段々の棚を滝のように落ちていく。棚の段差に当たるたび増える。下の壺に溜まった数がスコア。{twist}"),
 ("bouncepad", "跳ね台連鎖", "床に並んだ跳ね台に玉が落ちると高く跳ねて分裂する。跳ね台は{stage}に配置。数字は分裂の累計。タップで玉を落とす。{twist}"),
 ("swarm", "群れ分裂", "玉の群れが鳥の群れのように画面を飛び回り、画面端に触れた玉が分裂する。数字は玉の総数。タップで群れに1個追加。{twist}"),
 ("clicker", "タップ工場", "タップするたび数字が増え、増えた分で自動タップ速度も上がっていく（画面表示は数字だけ）。長押しで連打。{twist}"),
]

STAGES = ["斜めバーの多い部屋", "三角形だらけの部屋", "丸ペグだらけの部屋", "ひし形と横バーの部屋", "ランダム配置の障害物の部屋"]
TWISTS = [
 "基本形。倍率は2倍系、速さは標準。",
 "重力が弱くてふわふわ跳ねる版。",
 "重力が強くて速く荒い版。",
 "玉が小さくて数が増えやすい版（クールダウン0.3秒）。",
 "時々フィーバーが来て10秒間分裂が3倍になる版。",
]
COUNTS = ["40", "60", "80", "100", "120"]

os.makedirs("prompts100", exist_ok=True)
manifest = []
num = 0
for bi in range(20):
    slug, name, tmpl = FAMILIES[bi]
    lines = [f"# 実装指示：ドーパミンゲーム量産バッチ {bi+1:02d}/20（5本）\n", COMMON]
    for vi in range(5):
        num += 1
        fname = f"g{num:03d}.html"
        spec = tmpl.format(stage=STAGES[vi], twist=TWISTS[vi], count=COUNTS[vi])
        title = f"{name}{vi+1}"
        lines.append(f"## {num}本目：{title} → ファイル `{fname}`（<title>{title}</title>）\n{spec}\n")
        manifest.append(f"{fname}\t{title}")
    with open(f"prompts100/batch-{bi+1:02d}.md", "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
with open("manifest.tsv", "w", encoding="utf-8") as f:
    f.write("\n".join(manifest) + "\n")
print(f"generated {num} games, 20 batches")
